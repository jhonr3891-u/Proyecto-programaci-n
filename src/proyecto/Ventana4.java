    private void jBproduccionestimadaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBproduccionestimadaActionPerformed
        if (cantidadLeche <= 0) {
            JOptionPane.showMessageDialog(this, "No se recibieron datos válidos de cantidad de leche.", "Error de Datos", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String mensaje = "";

        // Lógica de cálculo según el producto recomendado
        if (productoRecomendado.equalsIgnoreCase("Yogur o Mantequilla")) {
            float estimacionYogur = cantidadLeche * 0.96f; // Rendimiento ~96%
            float estimacionMantequilla = cantidadLeche * 0.04f; // Rendimiento ~4%

            mensaje = "Con " + cantidadLeche + " L de leche puedes producir aproximadamente:\n\n" +
                      "• Yogur: " + String.format("%.2f", estimacionYogur) + " Litros\n" +
                      "• Mantequilla: " + String.format("%.2f", estimacionMantequilla) + " Kg";

        } else if (productoRecomendado.equalsIgnoreCase("Queso")) {
            float estimacionQueso = cantidadLeche * 0.11f; // Rendimiento ~11% (11 kg por cada 100 L)

            mensaje = "Con " + cantidadLeche + " L de leche puedes producir aproximadamente:\n\n" +
                      "• Queso: " + String.format("%.2f", estimacionQueso) + " Kg";

        } else {
            mensaje = "El estado actual del producto es '" + productoRecomendado + "', por lo que no es apto para producción.";
        }

        JOptionPane.showMessageDialog(this, mensaje, "Estimación de Producción", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jBproduccionestimadaActionPerformed

